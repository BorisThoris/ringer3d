// Writes roblox/tests/forge.luau: the TypeScript Marble Forge's output for a spread of seeds and
// uids, and the Luau that checks Ringer.Forge gives exactly the same marbles. Run it after any
// change to packages/marble-forge/src, then run the test on a cloud server:
//   npx esbuild roblox/scripts/forge-fixtures.ts --bundle --platform=node --outfile=roblox/build/forge-fixtures.cjs && node roblox/build/forge-fixtures.cjs
//   node roblox/scripts/run-luau.mjs roblox/tests/forge.luau <version>
import { writeFileSync } from 'node:fs';
import { generateMarble, marbleFixtures, RARITY } from '../../packages/marble-forge/src/generate';
import { localUid, mintCollectible } from '../../packages/marble-forge/src/collectible';
import { Rng } from '../../packages/marble-forge/src/rng';

const lua = (v: unknown): string => {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : v.toPrecision(17);
  if (typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) return `{ ${v.map(lua).join(', ')} }`;
  return `{ ${Object.entries(v as Record<string, unknown>).map(([k, x]) => `${k} = ${lua(x)}`).join(', ')} }`;
};

const marbleFields = (m: ReturnType<typeof generateMarble>) => ({
  seed: m.seed, id: m.id, name: m.name, tier: m.tier, pattern: m.pattern, finish: m.finish, scheme: m.scheme,
  base: m.base, accent: m.accent, accent2: m.accent2, clarity: m.clarity, glow: m.glow, sparkle: m.sparkle,
  effect: m.effect, effectColor: m.effectColor, shape: m.shape,
});

// Seeds: the generator's own fixtures, a spread across 32 bits, and enough phenomena to cover each one.
const seeds: { seed: number; tier?: string }[] = [];
for (const m of marbleFixtures()) seeds.push({ seed: m.seed, tier: seeds.length >= 40 ? m.tier : undefined });
const rng = new Rng(20261031);
for (let i = 0; i < 160; i++) seeds.push({ seed: Math.floor(rng.next() * 4294967296) });
for (const t of RARITY.map((r) => r.tier)) for (let i = 0; i < 12; i++) seeds.push({ seed: 900000 + i * 31, tier: t });
// Two Mythic seeds for every phenomenon, so each effect's colour range is covered.
{
  const seen: Record<string, number> = {};
  for (let s = 5000000; Object.keys(seen).length < 6 || Object.values(seen).some((n) => n < 2); s++) {
    const e = generateMarble(s, 'Mythic').effect;
    if (e !== 'none' && (seen[e] ?? 0) < 2) {
      seen[e] = (seen[e] ?? 0) + 1;
      seeds.push({ seed: s, tier: 'Mythic' });
    }
  }
}

const marbles = seeds.map(({ seed, tier }) => ({ seed, tier: tier ?? null, want: marbleFields(generateMarble(seed, tier as never)) }));

// Collectibles: local-style uids, Roblox-style uids, legacy "g" ids, forced tiers.
const uids: { uid: string; tier?: string }[] = [];
for (let i = 0; i < 80; i++) uids.push({ uid: localUid(Math.floor(rng.next() * 4294967296), Math.floor(rng.next() * 4294967296)) });
for (let i = 0; i < 40; i++) uids.push({ uid: 'R' + localUid(Math.floor(rng.next() * 4294967296), Math.floor(rng.next() * 4294967296)).slice(1) });
for (const s of [1, 7920, 123456789]) uids.push({ uid: `g${s}` });
for (const t of RARITY.map((r) => r.tier)) uids.push({ uid: 'Rdeadbeef0000beef', tier: t });
const collectibles = uids.map(({ uid, tier }) => {
  const c = mintCollectible(uid, tier as never);
  return { uid, tier: tier ?? null, want: { id: c.id, tier: c.tier, float: c.float, wear: c.wear, pattern: c.pattern, shiny: c.shiny, effect: c.effect, traits: c.traits, name: c.marble.name, finish: c.marble.finish, sparkle: c.marble.sparkle } };
});

const effects = new Set(marbles.map((m) => m.want.effect));
const body = `-- Generated by roblox/scripts/forge-fixtures.ts from packages/marble-forge. Do not edit.
-- Ringer.Forge must give exactly the TypeScript generator's marbles (${marbles.length} seeds, ${collectibles.length} uids;
-- phenomena covered: ${[...effects].sort().join(', ')}).
local Forge = require(game.ReplicatedStorage.Ringer.Forge)
local MARBLES = ${lua(marbles)}
local COLLECTIBLES = ${lua(collectibles)}

local fails, checked = {}, 0
local function same(a, b)
	if type(a) == "number" and type(b) == "number" then
		return math.abs(a - b) < 1e-9
	end
	if type(a) == "table" and type(b) == "table" then
		for k, v in pairs(a) do
			if not same(v, b[k]) then
				return false
			end
		end
		for k in pairs(b) do
			if a[k] == nil then
				return false
			end
		end
		return true
	end
	return a == b
end
local function check(label, want, got)
	for k, v in pairs(want) do
		checked += 1
		if not same(v, got[k]) then
			table.insert(fails, label .. "." .. k .. ": want " .. tostring(typeof(v) == "table" and game:GetService("HttpService"):JSONEncode(v) or v) .. " got " .. tostring(typeof(got[k]) == "table" and game:GetService("HttpService"):JSONEncode(got[k]) or got[k]))
		end
	end
end
for _, f in ipairs(MARBLES) do
	check("seed " .. string.format("%d", f.seed), f.want, Forge.generate(f.seed, f.tier))
end
for _, f in ipairs(COLLECTIBLES) do
	local c = Forge.mint(f.uid, f.tier)
	check("uid " .. f.uid, f.want, { id = c.id, tier = c.tier, float = c.float, wear = c.wear, pattern = c.pattern, shiny = c.shiny, effect = c.effect, traits = c.traits, name = c.marble.name, finish = c.marble.finish, sparkle = c.marble.sparkle })
end
print(string.format("forge parity: %d values checked, %d mismatches", checked, #fails))
for i = 1, math.min(#fails, 25) do
	print("MISMATCH " .. fails[i])
end
print(string.format("phenomenon odds %.4f%%", Forge.phenomenonOdds()))
return #fails == 0 and "PASS" or ("FAIL " .. #fails)
`;
writeFileSync('roblox/tests/forge.luau', body);
console.log(`wrote roblox/tests/forge.luau: ${marbles.length} marbles, ${collectibles.length} collectibles, effects ${[...effects].join(',')}`);
