// Writes roblox/tests/maps.luau: the web game's generated maps (src/game/maps.ts) for every field,
// difficulty and a spread of seeds, and the Luau that checks Ringer.Maps lays out the same ones.
//   npx esbuild roblox/scripts/maps-fixtures.ts --bundle --platform=node --outfile=roblox/build/maps-fixtures.cjs && node roblox/build/maps-fixtures.cjs
//   node roblox/scripts/run-luau.mjs roblox/tests/maps.luau <version>
import { writeFileSync } from 'node:fs';
import { DIFFICULTIES, generateMap } from '../../src/game/maps';

const ARENAS = ['desk', 'culdesac', 'grass', 'sand', 'ice', 'gravel', 'minigolf'] as const;
const SEEDS = [1, 42, 7919, 123456, 2026103101];

const lua = (v: unknown): string => {
  if (v === null || v === undefined) return 'nil';
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'number') return Number.isInteger(v) ? String(v) : v.toPrecision(17);
  if (typeof v === 'boolean') return String(v);
  if (Array.isArray(v)) return `{ ${v.map(lua).join(', ')} }`;
  return `{ ${Object.entries(v as Record<string, unknown>).map(([k, x]) => `${k} = ${lua(x)}`).join(', ')} }`;
};

const maps = [];
let pieces = 0;
for (const arena of ARENAS)
  for (const difficulty of DIFFICULTIES)
    for (const seed of SEEDS) {
      const m = generateMap({ arena, difficulty, seed });
      pieces += m.pieces.length;
      maps.push({ arena, difficulty, seed, name: m.name, pieces: m.pieces });
    }

const body = `-- Generated by roblox/scripts/maps-fixtures.ts from src/game/maps.ts. Do not edit.
-- Ringer.Maps must lay out the web game's maps: ${maps.length} maps, ${pieces} pieces.
local Maps = require(game.ReplicatedStorage.Ringer.Maps)
local WANT = ${lua(maps)}

local fails, checked, maps = {}, 0, 0
local function close(a, b)
	if type(a) == "number" and type(b) == "number" then
		-- Positions are rounded to 0.001; allow one step for a libm difference in the last bit.
		return math.abs(a - b) <= 0.0011
	end
	return a == b
end
for _, w in ipairs(WANT) do
	local got = Maps.generate(w.arena, w.difficulty, w.seed)
	local label = w.arena .. "/" .. w.difficulty .. "/" .. string.format("%d", w.seed)
	local ok = got.name == w.name and #got.pieces == #w.pieces
	if not ok then
		table.insert(fails, string.format("%s: want %q %d pieces, got %q %d", label, w.name, #w.pieces, got.name, #got.pieces))
	else
		for i, wp in ipairs(w.pieces) do
			for k, v in pairs(wp) do
				checked += 1
				if not close(v, got.pieces[i][k]) then
					ok = false
					table.insert(fails, string.format("%s piece %d %s: want %s got %s", label, i, k, tostring(v), tostring(got.pieces[i][k])))
					break
				end
			end
		end
	end
	if ok then
		maps += 1
	end
end
print(string.format("maps parity: %d of %d maps identical, %d values checked, %d mismatches", maps, #WANT, checked, #fails))
for i = 1, math.min(#fails, 25) do
	print("MISMATCH " .. fails[i])
end
return #fails == 0 and "PASS" or ("FAIL " .. #fails)
`;
writeFileSync('roblox/tests/maps.luau', body);
console.log(`wrote roblox/tests/maps.luau: ${maps.length} maps, ${pieces} pieces`);
